export function genreByIndex(index: number): string | undefined {
  return Number.isInteger(index) ? ID3_GENRES[index] : undefined;
}

/**
 * ID3v2 genre text: "Rock", "17", "(17)", "(17)(18)", "(17)Rock", "(RX)", "(CR)", and "((" for a literal "(".
 * Numbers become names. A name after the numbers wins, because it is what the tagger meant to show.
 */
export function resolveGenre(raw: string): string {
  const text = raw.trim();
  if (text.length === 0) return '';
  if (/^\d{1,3}$/.test(text)) return genreByIndex(Number(text)) ?? text;
  let rest = text;
  const names: string[] = [];
  for (;;) {
    if (rest.startsWith('((')) break;
    const match = /^\((\d{1,3}|RX|CR)\)/.exec(rest);
    if (!match) break;
    const code = match[1] ?? '';
    if (code === 'RX') names.push('Remix');
    else if (code === 'CR') names.push('Cover');
    else names.push(genreByIndex(Number(code)) ?? code);
    rest = rest.slice(match[0].length);
  }
  if (rest.startsWith('((')) rest = rest.slice(1);
  rest = rest.trim();
  if (rest.length > 0) return rest;
  return names.join(' / ');
}
