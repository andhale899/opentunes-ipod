/**
 * Writes docs/DEVICE-SUPPORT.md from the device registry.
 * Run with `npm run docs:devices`. CI fails if the committed file is stale.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { devices } from '../src/devices/registry';
import type { DeviceModel, MediaKind } from '../src/devices/types';

const MEDIA_LABELS: Record<MediaKind, string> = {
  music: 'Music',
  video: 'Video',
  podcast: 'Podcasts',
  audiobook: 'Audiobooks',
  photo: 'Photos',
  notes: 'Notes',
};

const STATUS_LABELS = {
  'hardware-tested': 'Tested on hardware',
  'spec-sourced': 'From specification, not run on hardware',
  unverified: 'Unverified',
} as const;

function cell(text: string): string {
  return text.replace(/\|/g, '\\|');
}

function summaryTable(): string[] {
  const rows = devices.map((device) =>
    [
      device.name,
      device.years,
      device.connector,
      device.databaseFormat,
      device.checksum ?? 'unknown',
      STATUS_LABELS[device.verification],
    ]
      .map(cell)
      .join(' | '),
  );
  return [
    '| Model | Years | Connector | Database | Checksum | Status |',
    '| --- | --- | --- | --- | --- | --- |',
    ...rows.map((row) => `| ${row} |`),
  ];
}

function detailSection(device: DeviceModel): string[] {
  const lines: string[] = [`### ${device.name}`, ''];
  lines.push(`Status: ${STATUS_LABELS[device.verification]}.`, '');
  lines.push(`Connector: ${device.connector}. Database: ${device.databaseFormat}. Checksum: ${device.checksum ?? 'unknown'}.`);
  if (device.checksumBasis) lines.push('', `Checksum basis: ${device.checksumBasis}`);

  if (device.media) {
    lines.push('', '| Media | Support | Detail |', '| --- | --- | --- |');
    for (const kind of Object.keys(MEDIA_LABELS) as MediaKind[]) {
      const support = device.media[kind];
      if (!support) continue;
      const formats = (support.formats ?? [])
        .map((format) => {
          if ('profiles' in format) {
            const bitrate = format.maxVideoBitrateKbps ? `, up to ${format.maxVideoBitrateKbps} kbps` : '';
            const level = format.level ? `, level ${format.level}` : '';
            const codec = format.codec === 'h264' ? 'H.264' : 'MPEG-4';
            return `${codec} ${format.profiles.join('/')}${level}, ${format.maxWidth}x${format.maxHeight} at ${format.maxFps} fps${bitrate}, ${format.audio}, ${format.containers.join(' ')}`;
          }
          const range = format.bitrateKbps ? ` ${format.bitrateKbps.min}-${format.bitrateKbps.max} kbps` : '';
          const vbr = format.variableBitrate ? ' (VBR)' : '';
          const rate = format.maxSampleRateHz ? `, up to ${format.maxSampleRateHz / 1000} kHz` : '';
          const depth = format.maxBitDepth ? `, ${format.maxBitDepth}-bit` : '';
          const note = format.note ? ` (${format.note})` : '';
          return `${format.codec}${range}${vbr}${rate}${depth}${note}`;
        })
        .join('; ');
      const detail = [formats, support.note].filter(Boolean).join('. ');
      lines.push(`| ${MEDIA_LABELS[kind]} | ${support.status} | ${cell(detail)} |`);
    }
  }

  if (device.deviceDeclared) {
    const declared = device.deviceDeclared;
    const formats = (list: { id: number; width: number; height: number }[] | undefined) =>
      (list ?? []).map((format) => `${format.id} (${format.width}x${format.height})`).join(', ');
    lines.push('', `Declared by the device itself (\`${declared.source}\`):`, '', `- ${declared.note}`);
    if (declared.volumeFormat) lines.push(`- Disk format: ${declared.volumeFormat}`);
    if (declared.maxTracks) lines.push(`- Up to ${declared.maxTracks} tracks, files up to ${declared.maxFileSizeGB ?? '?'} GB`);
    const features = Object.entries(declared.features ?? {}).filter(([, on]) => on).map(([name]) => name);
    if (features.length) lines.push(`- Features: ${features.join(', ')}`);
    if (declared.images?.albumArt) lines.push(`- Album art formats: ${formats(declared.images.albumArt)}`);
    if (declared.images?.photo) lines.push(`- Photo formats: ${formats(declared.images.photo)}`);
    if (declared.images?.chapter) lines.push(`- Chapter image formats: ${formats(declared.images.chapter)}`);
  }

  if (device.sources.length) {
    lines.push('', 'Sources:');
    for (const source of device.sources) lines.push(`- [${source.label}](${source.url}), read ${source.retrieved}`);
  }
  if (device.notes.length) {
    lines.push('', 'Notes:');
    for (const note of device.notes) lines.push(`- ${note}`);
  }
  lines.push('');
  return lines;
}

const researched = devices.filter((device) => device.media !== null);

const out = [
  '# Device support',
  '',
  '<!-- Generated by `npm run docs:devices` from core/src/devices/registry.ts. Do not edit by hand. -->',
  '',
  'Every row says how far it can be trusted. "Tested on hardware" means a sync was run on a real iPod of that model and the result recorded. Nothing has reached that level yet.',
  '',
  'Capability limits are only filled in once they have been read from a published specification. Models without them show identity facts only.',
  '',
  '## All models',
  '',
  ...summaryTable(),
  '',
  '## Researched models',
  '',
  ...researched.flatMap(detailSection),
].join('\n');

const target = fileURLToPath(new URL('../../docs/DEVICE-SUPPORT.md', import.meta.url));
writeFileSync(target, `${out.trimEnd()}\n`);
console.log(`Wrote ${target}`);
